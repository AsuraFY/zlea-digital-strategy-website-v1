function applyLanguage(lang) {
  currentLang = lang === "fr" ? "fr" : "en";
  document.documentElement.lang = currentLang;
  try { localStorage.setItem("zlea-lang", currentLang); } catch {}
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const value = translations[currentLang][el.dataset.i18n];
    if (value) el.textContent = value;
  });
  const switcher = document.getElementById("langSwitch");
  switcher.textContent = currentLang === "en" ? "FR" : "EN";
  switcher.setAttribute("aria-label", currentLang === "en" ? "Passer en français" : "Switch to English");
  document.querySelector("nav").setAttribute("aria-label", currentLang === "en" ? "Main navigation" : "Navigation principale");
  const filters = document.querySelector(".news-filters");
  if (filters) filters.setAttribute("aria-label", currentLang === "en" ? "News categories" : "Catégories d’actualités");
  document.title = (pageTitles[currentLang][document.body.dataset.page] || "ZLEA") + " | ZLEA Digital Safety";
  document.getElementById("chatToggle").setAttribute("aria-label", translations[currentLang].chat_open);
  document.getElementById("chatClose").setAttribute("aria-label", translations[currentLang].chat_close);
  document.querySelectorAll(".chat-route").forEach(link => { link.textContent = translations[currentLang][link.dataset.label]; });
  renderNews();
  updateHeaderHeight();
}
document.getElementById("langSwitch").addEventListener("click", () => applyLanguage(currentLang === "en" ? "fr" : "en"));

