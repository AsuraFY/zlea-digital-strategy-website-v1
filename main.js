function renderNews() {
  const results = document.getElementById("news-results");
  if (!results) return;
  results.replaceChildren();
  const items = (window.zleaContent?.news || []).filter(item => selectedNewsFilter === "all" || item.category === selectedNewsFilter);
  let rendered = 0;
  items.forEach(item => {
    // Publish only complete, dated, bilingual entries with a real HTTPS source.
    if (!item.title?.en || !item.title?.fr || !item.summary?.en || !item.summary?.fr || !item.source || !/^\d{4}-\d{2}-\d{2}$/.test(item.date)) return;
    let url;
    try { url = new URL(item.url); } catch { return; }
    if (url.protocol !== "https:") return;
    const col = document.createElement("div"); col.className = "col-md-6 col-lg-4";
    const card = document.createElement("article"); card.className = "resource-card h-100";
    const tag = document.createElement("span"); tag.className = "tag";
    tag.textContent = translations[currentLang]["filter_" + item.category] || item.category;
    const heading = document.createElement("h2"); heading.className = "h5"; heading.textContent = item.title[currentLang];
    const summary = document.createElement("p"); summary.textContent = item.summary[currentLang];
    const meta = document.createElement("p"); meta.className = "availability-note"; meta.textContent = item.source + " · " + item.date;
    const link = document.createElement("a"); link.href = url.href; link.rel = "noreferrer"; link.textContent = translations[currentLang].source_link;
    card.append(tag, heading, meta, summary);
    if (item.whyItMatters?.[currentLang]) {
      const whyHeading = document.createElement("h3"); whyHeading.className = "h6";
      whyHeading.textContent = translations[currentLang].why_matters;
      const why = document.createElement("p"); why.textContent = item.whyItMatters[currentLang];
      card.append(whyHeading, why);
    }
    card.append(link); col.append(card); results.append(col); rendered++;
  });
  const empty = document.getElementById("news-empty");
  empty.hidden = rendered > 0;
  empty.textContent = translations[currentLang][selectedNewsFilter === "all" ? "news_empty" : "news_no_match"];
}
document.querySelectorAll("[data-news-filter]").forEach(button => button.addEventListener("click", () => {
  selectedNewsFilter = button.dataset.newsFilter;
  document.querySelectorAll("[data-news-filter]").forEach(item => item.setAttribute("aria-pressed", String(item === button)));
  renderNews();
}));

const chatToggle = document.getElementById("chatToggle");
const chatPanel = document.getElementById("chatPanel");
const chatClose = document.getElementById("chatClose");
const chatBody = document.getElementById("chatBody");
chatToggle.setAttribute("aria-controls", "chatPanel");
chatToggle.setAttribute("aria-expanded", "false");
chatPanel.inert = true;
function toggleChat(open) {
  chatPanel.classList.toggle("open", open);
  chatPanel.setAttribute("aria-hidden", String(!open));
  chatToggle.setAttribute("aria-expanded", String(open));
  chatPanel.inert = !open;
  if (open) chatClose.focus(); else chatToggle.focus();
}
chatToggle.addEventListener("click", () => toggleChat(!chatPanel.classList.contains("open")));
chatClose.addEventListener("click", () => toggleChat(false));
document.addEventListener("keydown", event => { if (event.key === "Escape" && chatPanel.classList.contains("open")) toggleChat(false); });
const chatRoutes = {account:["get-help.html#help-form","nav_help"],breakup:["resources.html","nav_resources"],privacy:["news.html","nav_news"]};
document.querySelectorAll("[data-chat]").forEach(button => button.addEventListener("click", () => {
  const [href, key] = chatRoutes[button.dataset.chat];
  const link = document.createElement("a");
  link.className = "bot-message chat-route d-block mt-2";
  link.href = href;
  link.dataset.label = key;
  link.textContent = translations[currentLang][key];
  link.addEventListener("click", () => toggleChat(false));
  chatBody.append(link); chatBody.scrollTop = chatBody.scrollHeight;
}));
