let currentLang = localStorage.getItem("zlea-lang") || "en";

function applyLanguage(lang) {
  currentLang = lang;
  document.documentElement.lang = lang;
  localStorage.setItem("zlea-lang", lang);

  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.dataset.i18n;
    if (translations[lang][key]) el.textContent = translations[lang][key];
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const key = el.dataset.i18nPlaceholder;
    if (translations[lang][key]) el.placeholder = translations[lang][key];
  });

  document.getElementById("langSwitch").textContent = lang === "en" ? "FR" : "EN";
}

document.getElementById("langSwitch").addEventListener("click", () => {
  applyLanguage(currentLang === "en" ? "fr" : "en");
});

applyLanguage(currentLang);

const chatToggle = document.getElementById("chatToggle");
const chatPanel = document.getElementById("chatPanel");
const chatClose = document.getElementById("chatClose");
const chatBody = document.getElementById("chatBody");

function toggleChat(open) {
  chatPanel.classList.toggle("open", open);
  chatPanel.setAttribute("aria-hidden", String(!open));
}

chatToggle.addEventListener("click", () => toggleChat(!chatPanel.classList.contains("open")));
chatClose.addEventListener("click", () => toggleChat(false));

